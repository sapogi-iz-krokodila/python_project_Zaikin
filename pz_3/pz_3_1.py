'''1. Даны два целых числа: A, B. Проверить истинность высказывания: «Хотя бы одно
из чисел A и B нечетное».'''
while True:
    try:
        a = int(input("Введите значение: "))
        b = int(input("Введите значение: "))
        break
    except ValueError:
         print("ошибка введите коректное значение:")

c = (a % 2) != 0
f = (b % 2) != 0
