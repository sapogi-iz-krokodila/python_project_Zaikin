'''Дана арифметическая прогрессия а1=1, а2=4, а3=7, а4=10, а5=13, … Составить
программу, которая каждый элемент прогрессии разделит на 2 и результат округлит
до ближайшего целого.'''

number = int(input("Введите количество элементов прогрессии: "))

current_element = 1
i =1


while i <= number:
    result = round(current_element / 2)
    print(f"Элемент {current_element} после деления на 2 и округления: {result}")
    current_element += 3
    i += 1